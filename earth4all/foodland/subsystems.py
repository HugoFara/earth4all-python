"""Equations of the FoodLand sector.

Transcribed from `src/foodland/subsystems.jl` of Earth4All.jl, which
transcribes the Vensim model. Each equation is kept on a single line,
however long, so that the three can be read side by side.
"""

from ..functions import add_equation, interpolate, ramp, withlookup
from ..symbolics import D, exp, ifelse, log, max, min, t
from ..system import ODESystem
from .initialisations import _inits
from .parameters import _params
from .tables import _ranges, _tables


def foodland(name="foo", params=None, inits=None, tables=None, ranges=None):
    """The equations of the FoodLand sector."""
    params = _params if params is None else params
    inits = _inits if inits is None else inits
    tables = _tables if tables is None else tables
    ranges = _ranges if ranges is None else ranges
    sys = ODESystem(name)
    eqs = sys.equations

    AFGDP = sys.parameter("AFGDP", params["AFGDP"], "Agriculture as Fraction of GDP")
    CBECLE = sys.parameter("CBECLE", params["CBECLE"], "sFBeoCLE<0: Crob Balance Effect on CropLand Expansion")
    CO2ARA = sys.parameter("CO2ARA", params["CO2ARA"], "CO2 Absorbed in Reg Ag tCO2/ha/y")
    CO2C2022 = sys.parameter("CO2C2022", params["CO2C2022"], "Climate.CO2 concentration in 2022 ppm")
    CO2CEACY = sys.parameter("CO2CEACY", params["CO2CEACY"], "sCO2CeoACY>0: CO2 Concentration Effect on Average Crop Yeld")
    CO2RHFC = sys.parameter("CO2RHFC", params["CO2RHFC"], "CO2 Release per Ha of Forest Cut tCO2/ha")
    CRDRA = sys.parameter("CRDRA", params["CRDRA"], "Cost Reduction per Doubling in Regenerative Agriculture")
    CTF = sys.parameter("CTF", params["CTF"], "Cost per Ton Fertilizer dollar/t")
    CYRA = sys.parameter("CYRA", params["CYRA"], "Crop Yield in Reg Ag t-crop/ha/y")
    DRC = sys.parameter("DRC", params["DRC"], "Desired Reserve Capacity")
    ECRA22 = sys.parameter("ECRA22", params["ECRA22"], "Extra Cost of Reg Ag in 2022 dollar/ha/y")
    EGB22 = sys.parameter("EGB22", params["EGB22"], "Experience Gained Before 2022 Mha")
    EROCFSP = sys.parameter("EROCFSP", params["EROCFSP"], "Extra ROC in Food Sector Productivity from 2022 1/y")
    FCG = sys.parameter("FCG", params["FCG"], "Fraction Cleared for Grazing")
    FF80 = sys.parameter("FF80", inits["CRLA"] * params["FU80"], "Food Footprint in 1980")
    FFLREOGRRM = sys.parameter("FFLREOGRRM", params["FFLREOGRRM"], "sFFLReoOGRR<0: Fraction Forestry Land Remaining Effect on Old Growth Removal Rate Multiplier")
    FU80 = sys.parameter("FU80", params["FU80"], "Fertilizer Use in 1980 Mt/y")
    FUELER = sys.parameter("FUELER", params["FUELER"], "sFUeoLER>0: Fertilizer Use Effect on Land Erosion Rate")
    FUESQ = sys.parameter("FUESQ", params["FUESQ"], "sFUeoSQ<0: Fertilizer Use Effect on Soil Quality")
    GCWR = sys.parameter("GCWR", params["GCWR"], "Goal for Crop Waste Reduction")
    GFNRM = sys.parameter("GFNRM", params["GFNRM"], "Goal for Fraction New Red Meat")
    GFRA = sys.parameter("GFRA", params["GFRA"], "Goal for fraction regenerative agriculture")
    KCKRM = sys.parameter("KCKRM", params["KCKRM"], "Kg-Crop per Kg-Red-Meat")
    LER80 = sys.parameter("LER80", params["LER80"], "Land Erosion Rate in 1980 1/y")
    MFAM = sys.parameter("MFAM", params["MFAM"], "Max Forest Absorption Multiplier")
    OGRR80 = sys.parameter("OGRR80", params["OGRR80"], "OGRR in 1980 1/y")
    OW2022 = sys.parameter("OW2022", params["OW2022"], "Climate.Observed Warming in 2022 deg C")
    OWEACY = sys.parameter("OWEACY", params["OWEACY"], "sOWeoACY<0: Observed Warming Effect on Average Crop Yeld")
    ROCFP = sys.parameter("ROCFP", params["ROCFP"], "ROC in Fertilizer Productivity 1/y")
    ROCFSP = sys.parameter("ROCFSP", params["ROCFSP"], "ROC in Food Sector Productivity 1/y")
    SFU = sys.parameter("SFU", params["SFU"], "Sustainable Fertiliser Use kgN/ha/y")
    SSP2LMA = sys.parameter("SSP2LMA", params["SSP2LMA"], "SSP2 land management action from 2022?")
    TCTB = sys.parameter("TCTB", params["TCTB"], "Ton Crops per Toe Biofuel")
    TFFLR = sys.parameter("TFFLR", params["TFFLR"], "Threshold FFLR")
    UDT = sys.parameter("UDT", params["UDT"], "Urban Development Time y")
    ULP = sys.parameter("ULP", params["ULP"], "Urban Land per Population ha/p")
    ACY = sys.variable("ACY", description="Average Crop Yield t-crop/ha/y")
    ALFL = sys.variable("ALFL", description="Acceptable Loss of Forestry Land (1)")
    AFSRA = sys.variable("AFSRA", description="Amount of Fertilizer Saved in Reg Ag kgN/ha/y")
    BALA = sys.variable("BALA", inits["BALA"], "BArren LAnd Mha")
    BIUS = sys.variable("BIUS", description="BIofuels USe Mtoe/y")
    CEM = sys.variable("CEM", description="Cropland Expansion Multiplier (1)")
    CIRA = sys.variable("CIRA", description="Cost Index for Regenerative Agriculture (1)")
    CO2AFL = sys.variable("CO2AFL", description="CO2 Absorption in Forestry Land GtCO2/y")
    CO2AFLH = sys.variable("CO2AFLH", description="CO2 Absorption in Forestry Land tCO2/ha/y")
    CO2ELULUC = sys.variable("CO2ELULUC", description="CO2 Emissions from LULUC GtCO2/y")
    CO2ELY = sys.variable("CO2ELY", description="CO2 Effect on Land Yield (1)")
    CO2RFC = sys.variable("CO2RFC", description="CO2 Release from Forest Cut GtCO2/y")
    COFE = sys.variable("COFE", description="COst of FErtilizer Gdollar/y")
    COFO = sys.variable("COFO", description="COst of FOod Gdollar/y")
    CRA = sys.variable("CRA", description="Cost of Regenerative Agriculture Gdollar/y")
    CRBA = sys.variable("CRBA", description="CRop BAlance (1)")
    CRBI = sys.variable("CRBI", description="CRops for BIofuel Mt-crop/y")
    CRDE = sys.variable("CRDE", description="CRop DEmand Mt-crop/y")
    CREX = sys.variable("CREX", description="CRopland EXpansion Mha/y")
    CREXR = sys.variable("CREXR", description="CRopland EXpansion Rate 1/y")
    CRLA = sys.variable("CRLA", inits["CRLA"], "CRopLAnd Mha")
    CRLO = sys.variable("CRLO", description="CRopland LOss Mha/y")
    CRSU = sys.variable("CRSU", description="CRop SUpply (after 20 % waste) Mt-crop/y")
    CRUS = sys.variable("CRUS", description="CRop USe Mt/y")
    CRUSP = sys.variable("CRUSP", description="CRop USe per Person t-crop/p/y")
    CSQCA = sys.variable("CSQCA", description="Change in Soil Quality in Conv Ag t-crop/ha/y/y")
    CSRA = sys.variable("CSRA", description="Crop Supply Reg Ag Mt-crop/y")
    CWR = sys.variable("CWR", description="Crop Waste Reduction (1)")
    DCS = sys.variable("DCS", description="Desired Crop Supply Mt-crop/y")
    DCSCA = sys.variable("DCSCA", description="Desired Crop Supply Conv Ag Mt-crop/y")
    DCYCA = sys.variable("DCYCA", description="Desired Crop Yield in Conv Ag t-crop/ha/y")
    DRM = sys.variable("DRM", description="Demand for Red Meat Mt-red-meat/y")
    DRMP = sys.variable("DRMP", description="Demand for Red Meat per Person kg-red-meat/p/y")
    ECFT = sys.variable("ECFT", description="Extra Cost of Food Turnaround Gdollar/y")
    ECFTSGDP = sys.variable("ECFTSGDP", description="Extra Cost of Food Turnaround as Share of GDP (1)")
    ECO2ARA = sys.variable("ECO2ARA", description="Extra CO2 Absorption in Reg Ag GtCO2/y")
    ECRA = sys.variable("ECRA", description="Extra Cost of Reg Ag dollar/ha/y")
    FAM = sys.variable("FAM", description="Forest Absorption Multipler (1)")
    FCR = sys.variable("FCR", description="Fertilizer Cost Reduction Gdollar/y")
    FEER = sys.variable("FEER", description="Fertilizer Effect on Erosion Rate (1)")
    FERM = sys.variable("FERM", description="FEed for Red Meat Mt-crop/y")
    FEUS = sys.variable("FEUS", description="FErtilizer USe Mt/y")
    FFI = sys.variable("FFI", description="Food Footprint Index (1980=1)")
    FFLR = sys.variable("FFLR", description="Fraction Forestry Land Remaining (1)")
    FFLREOGRR = sys.variable("FFLREOGRR", description="FFLReoOGRR")
    FNRM = sys.variable("FNRM", description="Fraction New Red Meat (1)")
    FOFO = sys.variable("FOFO", description="FOod FOotprint")
    FOLA = sys.variable("FOLA", inits["FOLA"], "FOrestry LAnd Mha")
    FPI = sys.variable("FPI", description="Fertilizer Productivity Index (1980=1)")
    FRA = sys.variable("FRA", description="Fraction Regenerative Agriculture (1)")
    FSPI = sys.variable("FSPI", description="Food Sector Productivity Index (1980=1)")
    FUCA = sys.variable("FUCA", description="Fertilizer Use in Conv Ag kgN/ha/y")
    FUP = sys.variable("FUP", description="FErtilizer USe per Person kg/p/y")
    GLY = sys.variable("GLY", description="Grazing Land Yield kg-red-meat/ha/y")
    GLY80 = sys.variable("GLY80", description="Grazing Land Yied in 1980 kg-red-meat/ha/y")
    GRLA = sys.variable("GRLA", inits["GRLA"], "GRazing LAnd Mha")
    IUL = sys.variable("IUL", description="Indicated Urban Land Mha")
    LERM = sys.variable("LERM", description="Land ERosion Multiplier (1)")
    LER = sys.variable("LER", description="Land Erosion Rate 1/y")
    LFL = sys.variable("LFL", description="Loss of Forest Land Mha/y")
    LOCR = sys.variable("LOCR", description="LOss of CRopland Mha/y")
    NDRA = sys.variable("NDRA", description="Number of Doublings in Reg Ag (1)")
    NFL = sys.variable("NFL", description="New Forestry Land Mha/y")
    NGL = sys.variable("NGL", description="New Grazing Land Mha/y")
    OGFA = sys.variable("OGFA", inits["OGFA"], "Old Growth Forest Area Mha 1")
    OGRE = sys.variable("OGRE", description="Old Growth Removal Mha/y")
    OGRR = sys.variable("OGRR", description="Old Growth Removal Rate 1/y")
    OGRRM = sys.variable("OGRRM", description="Old Growth Removal Rate Multiplier (1)")
    PCB = sys.variable("PCB", description="Perceived Crop Balance (1)")
    PRMGL = sys.variable("PRMGL", description="Potential Red Meat from Grazing Land Mt-red-meat/y")
    RAA = sys.variable("RAA", description="Regenerative Agriculture Area Mha")
    RMF = sys.variable("RMF", description="Red Meat from Feedlots Mt-red-meat/y")
    RMGL = sys.variable("RMGL", description="Red Meat from Grazing Land Mt-red-meat/y")
    RMSP = sys.variable("RMSP", description="Red meat Supply per Person kg-red-meat/p/y")
    ROCSQCA = sys.variable("ROCSQCA", description="ROC in Soil Quality in Conv Ag 1/y")
    SQICA = sys.variable("SQICA", inits["SQICA"], "Soil Quality Index in Conv Ag (1980=1)")
    TFA = sys.variable("TFA", description="Total Forest Area Mha")
    TFUCA = sys.variable("TFUCA", description="Traditional Fertilizer Use in Conv Ag kgN/ha/y")
    TUC = sys.variable("TUC", description="Traditional Use of Crops Mt/y")
    TUCERM = sys.variable("TUCERM", description="Traditional Use of Crops Ex Red Meat Mt/y")
    TUCERMP = sys.variable("TUCERMP", description="Traditional Use of Crops Ex Red Meat per Person kg-crop/p/y")
    TUCP = sys.variable("TUCP", description="Traditional Use of Crops per Person kg-crop/p/y")
    TUFRM = sys.variable("TUFRM", description="Traditional Use of Feed for Red Meat Mt-crop/y")
    TURMP = sys.variable("TURMP", description="Traditional Use of Red Meat per Person kg-red-meat/p/y")
    UREX = sys.variable("UREX", description="URban EXpansion Mha/y")
    URLA = sys.variable("URLA", inits["URLA"], "URban LAnd Mha")
    WELY = sys.variable("WELY", description="Warming Effect on Land Yield (1)")
    CO2CA = sys.variable("CO2CA")
    GDP = sys.variable("GDP")
    GDPP = sys.variable("GDPP")
    IPP = sys.variable("IPP")
    OW = sys.variable("OW")
    POP = sys.variable("POP")
    add_equation(eqs, ACY, (DCYCA * (1 - FRA) * SQICA + CYRA * FRA) * CO2ELY * WELY)
    add_equation(eqs, ALFL, 1 - exp(-FFLR / TFFLR))
    add_equation(eqs, AFSRA, 268 - SFU)
    add_equation(eqs, D(BALA), CRLO)
    add_equation(eqs, BIUS, withlookup(t, [(1980.0, 0.0), (1990.0, 0.0), (2000.0, 0.0), (2020.0, 0.0), (2100.0, 0.0)]))
    add_equation(eqs, CEM, ifelse(t > 2022, 1 - SSP2LMA * ramp(t, (1 - 0) / 78, 2022, 2100), 1))
    add_equation(eqs, CIRA, (1 - CRDRA)**NDRA)
    add_equation(eqs, CO2AFL, FOLA * (CO2AFLH / 1000) * CO2ELY * WELY)
    add_equation(eqs, CO2AFLH, 1.6 * FAM)
    add_equation(eqs, CO2ELULUC, CO2RFC - CO2AFL - ECO2ARA)
    add_equation(eqs, CO2ELY, ifelse(t > 2022, 1 + CO2CEACY * (CO2CA / CO2C2022 - 1), 1))
    add_equation(eqs, CO2RFC, ((OGRE + CREX) * CO2RHFC) / 1000)
    add_equation(eqs, COFE, FEUS * CTF / 1000)
    add_equation(eqs, COFO, AFGDP * GDP + CRA + COFE)
    add_equation(eqs, CRA, (ECRA * RAA) / 1000)
    add_equation(eqs, CRBA, CRUS / DCS)
    add_equation(eqs, CRBI, BIUS * TCTB)
    add_equation(eqs, CRDE, (TUCERM + FERM + CRBI))
    add_equation(eqs, CREX, ifelse(FOLA > 0, CRLA * CREXR, 0) * ALFL * CEM)
    add_equation(eqs, CREXR, 1 / 200 + CBECLE * (PCB - 1))
    add_equation(eqs, D(CRLA), CREX - CRLO - UREX)
    add_equation(eqs, CRLO, CRLA * LER)
    add_equation(eqs, CRSU, ACY * CRLA)
    add_equation(eqs, CRUS, CRSU * (1 + CWR))
    add_equation(eqs, CRUSP, CRUS / POP)
    add_equation(eqs, CSQCA, ROCSQCA * SQICA)
    add_equation(eqs, CSRA, CYRA * CRLA * FRA)
    add_equation(eqs, CWR, ramp(t, GCWR / IPP, 2022, 2022 + IPP))
    add_equation(eqs, DCS, CRDE)
    add_equation(eqs, DCSCA, DCS - CSRA)
    add_equation(eqs, DCYCA, DCSCA / (CRLA * (1 - FRA)))
    add_equation(eqs, DRM, ((POP * DRMP) / 1000) * (1 - FNRM))
    add_equation(eqs, DRMP, TURMP)
    add_equation(eqs, ECFT, CRA - FCR)
    add_equation(eqs, ECFTSGDP, ECFT / GDP)
    add_equation(eqs, ECO2ARA, RAA * CO2ARA / 1000)
    add_equation(eqs, ECRA, ECRA22 * CIRA)
    add_equation(eqs, FAM, ifelse(t > 2022, 1 + SSP2LMA * ramp(t, (MFAM - 1) / 78, 2022, 2100), 1))
    add_equation(eqs, FCR, (AFSRA / 1000) * RAA * CTF)
    add_equation(eqs, FEER, 1 + FUELER * (FUCA / SFU - 1))
    add_equation(eqs, FERM, RMF * KCKRM)
    add_equation(eqs, FEUS, CRLA * (1 - FRA) * FUCA / 1000)
    add_equation(eqs, FFI, FOFO / FF80)
    add_equation(eqs, FFLR, max(0, FOLA / inits["FOLA"]))
    add_equation(eqs, FFLREOGRR, max(1, 1 + FFLREOGRRM * (FFLR - TFFLR)))
    add_equation(eqs, FNRM, ramp(t, GFNRM / IPP, 2022, 2022 + IPP))
    add_equation(eqs, FOFO, CRLA * FEUS)
    add_equation(eqs, D(FOLA), NFL - CREX)
    add_equation(eqs, FPI, exp(ROCFP * (t - 1980)))
    add_equation(eqs, FRA, ramp(t, GFRA / IPP, 2022, 2020 + IPP))
    add_equation(eqs, FSPI, exp(ROCFSP * (t - 1980)) * ifelse(t > 2022, exp(EROCFSP * (t - 2022)), 1))
    add_equation(eqs, FUCA, TFUCA / FPI)
    add_equation(eqs, FUP, (FEUS / POP) * 1000)
    add_equation(eqs, GLY, GLY80 + 0 * CO2CA - 0 * OW)
    add_equation(eqs, GLY80, 14 * CO2ELY * WELY)
    add_equation(eqs, D(GRLA), NGL)
    add_equation(eqs, IUL, POP * ULP)
    add_equation(eqs, LERM, ifelse(t > 2022, 1 - SSP2LMA * ramp(t, (1 - 0) / 78, 2022, 2100), 1))
    add_equation(eqs, LER, LER80 * FEER * LERM)
    add_equation(eqs, LFL, OGRE + CREX)
    add_equation(eqs, LOCR, CRLO + UREX)
    add_equation(eqs, NDRA, log((RAA + EGB22) / EGB22) / 0.693)
    add_equation(eqs, NFL, OGRE * (1 - FCG))
    add_equation(eqs, NGL, OGRE * FCG)
    add_equation(eqs, D(OGFA), -NFL - NGL)
    add_equation(eqs, OGRE, OGFA * OGRR * OGRRM)
    add_equation(eqs, OGRR, OGRR80 * FFLREOGRR)
    add_equation(eqs, OGRRM, ifelse(t > 2022, 1 - SSP2LMA * ramp(t, (1 - 0) / 78, 2022, 2100), 1))
    add_equation(eqs, PCB, CRBA / (1 + DRC))
    add_equation(eqs, PRMGL, GRLA * GLY / 1000)
    add_equation(eqs, RAA, CRLA * FRA)
    add_equation(eqs, RMF, DRM - RMGL)
    add_equation(eqs, RMGL, min(DRM, PRMGL))
    add_equation(eqs, RMSP, (RMGL + RMF * min(1, CRBA)) * 1000 / POP)
    add_equation(eqs, ROCSQCA, 0 + FUESQ * (FUCA / SFU - 1))
    add_equation(eqs, D(SQICA), CSQCA)
    add_equation(eqs, TFA, OGFA + FOLA)
    add_equation(eqs, TFUCA, withlookup(DCYCA, [(1.0, 0.0), (2.0, 40.0), (2.5, 50.0), (3.0, 60.0), (3.5, 70.0), (4.5, 100.0), (6.5, 200.0), (10.0, 600.0)]))
    add_equation(eqs, TUC, TUCP * POP / 1000)
    add_equation(eqs, TUCERM, (TUC - TUFRM) / FSPI)
    add_equation(eqs, TUCERMP, TUCERM * 1000 / POP)
    add_equation(eqs, TUCP, withlookup(GDPP, [(0.0, 400.0), (6.1, 680.0), (8.7, 780.0), (13.9, 950.0), (20.0, 1050.0), (30.0, 1150.0), (40.0, 1250.0), (60.0, 1350.0), (100.0, 1550.0)]))
    add_equation(eqs, TUFRM, (((TURMP / 1000) * POP) - RMGL) * KCKRM)
    add_equation(eqs, TURMP, withlookup(GDPP, [(0.0, 0.0), (6.1, 6.0), (8.8, 8.5), (14.0, 13.0), (30.0, 27.0), (40.0, 32.0), (50.0, 33.0), (100.0, 25.0)]))
    add_equation(eqs, UREX, max(0, (IUL - URLA) / UDT))
    add_equation(eqs, D(URLA), UREX)
    add_equation(eqs, WELY, ifelse(t > 2022, 1 + OWEACY * (OW / OW2022 - 1), 1))
    return sys


def foodland_full_support(name="foo", params=None, inits=None, tables=None, ranges=None):
    """The FoodLand sector variables that other sectors provide, read from tabulated runs of the whole model instead."""
    params = _params if params is None else params
    inits = _inits if inits is None else inits
    tables = _tables if tables is None else tables
    ranges = _ranges if ranges is None else ranges
    sys = ODESystem(name)
    eqs = sys.equations

    CO2CA = sys.variable("CO2CA", description="Climate.CO2 Concentration in Atm ppm")
    GDP = sys.variable("GDP", description="Inventory.GDP")
    GDPP = sys.variable("GDPP", description="Population.GDP per Person kdollar/p/y")
    IPP = sys.variable("IPP", description="Wellbeing.Introduction Period for Policy y")
    OW = sys.variable("OW", description="Climate.Observed warming deg C")
    POP = sys.variable("POP", description="Population.Population Mp")
    add_equation(eqs, CO2CA, interpolate(t, tables["CO2CA"], ranges["CO2CA"]))
    add_equation(eqs, GDP, interpolate(t, tables["GDP"], ranges["GDP"]))
    add_equation(eqs, GDPP, interpolate(t, tables["GDPP"], ranges["GDPP"]))
    add_equation(eqs, IPP, interpolate(t, tables["IPP"], ranges["IPP"]))
    add_equation(eqs, OW, interpolate(t, tables["OW"], ranges["OW"]))
    add_equation(eqs, POP, interpolate(t, tables["POP"], ranges["POP"]))
    return sys


