"""Equations of the Energy sector.

Transcribed from `src/energy/subsystems.jl` of Earth4All.jl, which
transcribes the Vensim model. Each equation is kept on a single line,
however long, so that the three can be read side by side.
"""

from ..functions import add_equation, interpolate, ramp, step, withlookup
from ..symbolics import D, exp, ifelse, log, max, t
from ..system import ODESystem
from .initialisations import _inits
from .parameters import _params
from .tables import _ranges, _tables


def energy(name="ene", params=None, inits=None, tables=None, ranges=None):
    """The equations of the Energy sector."""
    params = _params if params is None else params
    inits = _inits if inits is None else inits
    tables = _tables if tables is None else tables
    ranges = _ranges if ranges is None else ranges
    sys = ODESystem(name)
    eqs = sys.equations

    MNFCO2PP = sys.parameter("MNFCO2PP", params["MNFCO2PP"], "Max non-fossil CO2 per person tCO2/p/y")
    FCO2SCCS2022 = sys.parameter("FCO2SCCS2022", params["FCO2SCCS2022"], "Fraction of CO2-sources with CCS in 2022")
    GFCO2SCCS = sys.parameter("GFCO2SCCS", params["GFCO2SCCS"], "Goal for fraction of CO2-sources with CCS")
    CCCSt = sys.parameter("CCCSt", params["CCCSt"], "Cost of CCS Dollar/tCO2")
    ROCTCO2PT = sys.parameter("ROCTCO2PT", params["ROCTCO2PT"], "ROC in tCO2 per toe 1/y")
    EROCEPA2022 = sys.parameter("EROCEPA2022", params["EROCEPA2022"], "Extra ROC in energy productivity after 2022 1/y")
    NIEE = sys.parameter("NIEE", params["NIEE"], "Normal increase in energy efficiency 1/y")
    GFNE = sys.parameter("GFNE", params["GFNE"], "Goal for fraction new electrification")
    FNE2022 = sys.parameter("FNE2022", params["FNE2022"], "Fraction new electrification in 2022")
    FNE1980 = sys.parameter("FNE1980", params["FNE1980"], "Fraction new electrification in 1980")
    EUEPRUNEFF = sys.parameter("EUEPRUNEFF", params["EUEPRUNEFF"], "Extra use of electricity per reduced use of non-el FF MWh/toe")
    ECRUNEFF = sys.parameter("ECRUNEFF", params["ECRUNEFF"], "Extra cost per reduced use og non-el FF Dollar/toe")
    GREF = sys.parameter("GREF", params["GREF"], "Goal for renewable el fraction")
    REFF2022 = sys.parameter("REFF2022", params["REFF2022"], "Renewable el fraction in 2022")
    REFF1980 = sys.parameter("REFF1980", params["REFF1980"], "Renewable el fraction in 1980")
    RCUT = sys.parameter("RCUT", params["RCUT"], "Renewable capacity up-time kh/y")
    RECT = sys.parameter("RECT", params["RECT"], "Renewable el contruction time y")
    LREC = sys.parameter("LREC", params["LREC"], "Life of renewable el capacity y")
    SWC1980 = sys.parameter("SWC1980", params["SWC1980"], "Sun and wind capacity in 1980 GW")
    CRDSWC = sys.parameter("CRDSWC", params["CRDSWC"], "Cost reduction per dubling of sun and wind capacity")
    CAPEXRE1980 = sys.parameter("CAPEXRE1980", params["CAPEXRE1980"], "CAPEX of renewable el in 1980 Dollar/W")
    CAPEXFED = sys.parameter("CAPEXFED", params["CAPEXFED"], "CAPEX fossil el Dollar/W")
    OPEXRED = sys.parameter("OPEXRED", params["OPEXRED"], "OPEX renewable el Dollar/kWh")
    OPEXFED = sys.parameter("OPEXFED", params["OPEXFED"], "OPEX fossil el Dollar/kWh")
    CNED = sys.parameter("CNED", params["CNED"], "Cost of Nuclear El Dollar/kWh")
    FREH = sys.parameter("FREH", params["FREH"], "Fraction of renewable electricity to hydrogen")
    KWEPKGH2 = sys.parameter("KWEPKGH2", params["KWEPKGH2"], "kWh electricity per kg of hydrogen")
    TPTH2 = sys.parameter("TPTH2", params["TPTH2"], "toe per tH2")
    BEM = sys.parameter("BEM", params["BEM"], "Biomass energy Mtoe/y")
    EFPP = sys.parameter("EFPP", params["EFPP"], "Efficiency of fossil power plant TWh-el/TWh-heat")
    TWHPEJCE = sys.parameter("TWHPEJCE", params["TWHPEJCE"], "TWh-heat per EJ - calorific equivalent")
    MTPEJCE = sys.parameter("MTPEJCE", params["MTPEJCE"], "Mtoe per EJ - calorific equivalent")
    EKHPY = sys.parameter("EKHPY", params["EKHPY"], "8 khours per year")
    FECCT = sys.parameter("FECCT", params["FECCT"], "Fossil el cap construction time y")
    NLFEC = sys.parameter("NLFEC", params["NLFEC"], "Normal life of fossil el capacity y")
    sFCUTLOFC = sys.parameter("sFCUTLOFC", params["sFCUTLOFC"], "sFCUTeoLOFC>0")
    NCUT = sys.parameter("NCUT", params["NCUT"], "Nuclear capacity up-time kh/y")
    TCE = sys.parameter("TCE", params["TCE"], "Traditional cost of electricity Dollar/kWh")
    AFMCM = sys.parameter("AFMCM", params["AFMCM"], "Adjustment factor to make cost match 1980 - 2022")
    TCFFFNEU = sys.parameter("TCFFFNEU", params["TCFFFNEU"], "Traditional cost of fossil fuels for non-el use Dollar/toe")
    TC = sys.parameter("TC", params["TC"], "Transmission cost Dollar/kWh")
    CNEL = sys.variable("CNEL", description="Cost of Nuclear ELectricity Gdollar/y")
    CO2NFIP = sys.variable("CO2NFIP", description="CO2 from non-fossil industrial processes GtCO2/y")
    FCO2SCCS = sys.variable("FCO2SCCS", description="Fraction of CO2-sources with CCS (1)")
    NFCO2PP = sys.variable("NFCO2PP", description="Non-fossil CO2 per person tCO2/p/y")
    CO2EI = sys.variable("CO2EI", description="CO2 from energy and industry GtCO2/y")
    CO2EP = sys.variable("CO2EP", description="CO2 from energy production GtCO2/y")
    CO2EMPP = sys.variable("CO2EMPP", description="CO2 EMissions per person tCO2/y")
    CCCSG = sys.variable("CCCSG", description="Cost of CCS GDollar/y")
    ICCSC = sys.variable("ICCSC", description="Installed CCS capacity GtCO2/y")
    TCO2PT = sys.variable("TCO2PT", description="tCO2 per toe")
    EEPI2022 = sys.variable("EEPI2022", inits["EEPI2022"], "Extra energy productivity index 2022=1")
    IEEPI = sys.variable("IEEPI", description="Increase in extra energy productivity index 1/y")
    TPPUEBEE = sys.variable("TPPUEBEE", description="Traditional per person use of electricity before EE MWh/p/y")
    TPPUFFNEUBEE = sys.variable("TPPUFFNEUBEE", description="Traditional per person use of fossil fuels for non-el-use before EE toe/p/y")
    DEBNE = sys.variable("DEBNE", description="Demand for electricity before NE TWh/y")
    DFFNEUBNE = sys.variable("DFFNEUBNE", description="Demand for fossil fuel for non-el use before NE Mtoe/y")
    FNE = sys.variable("FNE", description="Fraction new electrification (1)")
    ERDNEFFFNE = sys.variable("ERDNEFFFNE", description="Extra reduction in demand for non-el fossil fuel from NE Mtoe/y")
    CNE = sys.variable("CNE", description="Cost of new electrification GDollar/y")
    EIDEFNE = sys.variable("EIDEFNE", description="Extra increase in demand for electricity from NE TWh/y")
    DFFFNEU = sys.variable("DFFFNEU", description="Demand for fossil fuel for non-el use Mtoe/y")
    UFF = sys.variable("UFF", description="Use of fossil fuels Mtoe/y")
    DE = sys.variable("DE", description="Demand for electricity TWh/y")
    DRES = sys.variable("DRES", description="Desired renewable electricity share (1)")
    DSRE = sys.variable("DSRE", description="Desired supply of renewable electricity TWh/y")
    DREC = sys.variable("DREC", description="Desired renewable el capacity GW")
    DRECC = sys.variable("DRECC", description="Desired renewable el capacity change GW")
    REC = sys.variable("REC", inits["REC"], "Renewable electricity capacity GW")
    AREC = sys.variable("AREC", description="Addition of renewable el capacity GW/y")
    DIREC = sys.variable("DIREC", description="Discard of renewable el capacity GW/y")
    ASWC = sys.variable("ASWC", description="Addition of sun and wind capacity GW/y")
    ACSWCF1980 = sys.variable("ACSWCF1980", inits["ACSWCF1980"], "ACcumulated sun and wind capacity from 1980 GW")
    NDSWC = sys.variable("NDSWC", description="Number of doublings in sun and wind capacity (1)")
    CISWC = sys.variable("CISWC", description="Cost index for sun and wind capacity (1)")
    CAPEXRED = sys.variable("CAPEXRED", description="CAPEX renewable el dollar/W")
    CAPEXREG = sys.variable("CAPEXREG", description="CAPEX renewable el Gdollar/y")
    OPEXREG = sys.variable("OPEXREG", description="OPEX renewable el Gdollar/y")
    CRE = sys.variable("CRE", description="Cost of renewable electricity GDollar/y")
    CAPEXFEG = sys.variable("CAPEXFEG", description="CAPEX fossil el GDollar/y")
    OPEXFEG = sys.variable("OPEXFEG", description="OPEX fossil el GDollar/y")
    CFE = sys.variable("CFE", description="Cost of fossil electricity GDollar/y")
    CEL = sys.variable("CEL", description="Cost of electricity GDollar/y")
    REP = sys.variable("REP", description="Renewable electricity production TWh/y")
    GHMH2 = sys.variable("GHMH2", description="Green hydrogen MtH2/y")
    GHMt = sys.variable("GHMt", description="Green hydrogen Mtoe/y")
    RHP = sys.variable("RHP", description="Renewable heat production Mtoe/y")
    TWEPEJEE = sys.variable("TWEPEJEE", description="TWh-el per EJ - engineering equivalent")
    IIASAREP = sys.variable("IIASAREP", description="IIASA Renewable energy production EJ/yr")
    FTWEPMt = sys.variable("FTWEPMt", description="4 TWh-el per Mtoe")
    IIASAFEP = sys.variable("IIASAFEP", description="IIASA Fossil energy production EJ/yr")
    LCEP = sys.variable("LCEP", description="Low-carbon el production TWh/y")
    DFE = sys.variable("DFE", description="Demand for fossil electricity TWh/y")
    DFEC = sys.variable("DFEC", description="Desired fossil el capacity GW")
    DFECC = sys.variable("DFECC", description="Desired fossil el capacity change GW/y")
    AFEC = sys.variable("AFEC", description="Addition of fossil el capacity GW/y")
    FEC = sys.variable("FEC", inits["FEC"], "Fossil electricity capacity GW")
    LFEC = sys.variable("LFEC", description="Life of fossil el capacity y")
    DIFEC = sys.variable("DIFEC", description="DIscard of Fossil El Capacity GW/y")
    FCUT = sys.variable("FCUT", description="Fossil capacity up-time kh/y")
    FCUTLOFC = sys.variable("FCUTLOFC", description="FCUTeoLOFC (1)")
    FEP = sys.variable("FEP", description="Fossil Electricity Production TWh/y")
    NC = sys.variable("NC", description="Nuclear capacity GW")
    NEP = sys.variable("NEP", description="Nuclear electricity production TWh/y")
    EP = sys.variable("EP", description="Electricity production TWh/y")
    ELB = sys.variable("ELB", description="ELectricity balance (1)")
    FFPNE = sys.variable("FFPNE", description="Fraction fossil plus nuclear electricity (1)")
    EU = sys.variable("EU", description="Energy use Mtoe/y")
    EUPP = sys.variable("EUPP", description="Energy use per person toe/p/y")
    FFE = sys.variable("FFE", description="Fossil fuels for electricity Mtoe/y")
    TCEG = sys.variable("TCEG", description="Traditional cost of electricity GDollar/y")
    TCFFFNEUG = sys.variable("TCFFFNEUG", description="Traditional cost of fossil fuel for non-el use Gdollar/y")
    CFFFNEU = sys.variable("CFFFNEU", description="Cost of Fossil Fuel For Non-El Use Gdollar/y")
    CG = sys.variable("CG", description="Cost of grid GDollar/y")
    TGC = sys.variable("TGC", description="Traditional grid cost GDollar/y")
    TCEN = sys.variable("TCEN", description="Traditional Cost of ENergy Gdollar/y")
    TCENSGDP = sys.variable("TCENSGDP", description="Traditional cost of energy as share of GDP (1)")
    CE = sys.variable("CE", description="Cost of energy GDollar/y")
    RECTEC = sys.variable("RECTEC", description="Ratio of Energy cost to Trad Energy cost (1)")
    CESGDP = sys.variable("CESGDP", description="Cost of energy as share of GDP (1)")
    ECETSGDP = sys.variable("ECETSGDP", description="Extra cost of Energy Turnaround as share of GDP (1)")
    CAC = sys.variable("CAC")
    GDP = sys.variable("GDP")
    GDPP = sys.variable("GDPP")
    IPP = sys.variable("IPP")
    POP = sys.variable("POP")
    add_equation(eqs, CNEL, NEP * CNED)
    add_equation(eqs, NFCO2PP, MNFCO2PP * (1 - exp(-(GDPP / 10))))
    add_equation(eqs, CO2NFIP, (NFCO2PP / 1000) * POP * (1 - FCO2SCCS))
    add_equation(eqs, FCO2SCCS, FCO2SCCS2022 + ramp(t, (GFCO2SCCS - FCO2SCCS2022) / IPP, 2022, 2022 + IPP))
    add_equation(eqs, CO2EI, CO2EP + CO2NFIP)
    add_equation(eqs, CO2EP, UFF * (TCO2PT / 1000) * (1 - FCO2SCCS))
    add_equation(eqs, CO2EMPP, (CO2EI / POP) * 1000)
    add_equation(eqs, CCCSG, CCCSt * ICCSC)
    add_equation(eqs, ICCSC, FCO2SCCS * (CO2NFIP + CO2EP) / (1 - FCO2SCCS))
    add_equation(eqs, TCO2PT, 2.8 * exp(ROCTCO2PT * (t - 1980)))
    add_equation(eqs, D(EEPI2022), IEEPI)
    add_equation(eqs, IEEPI, EROCEPA2022 * 0 + step(t, EROCEPA2022, 2022))
    add_equation(eqs, TPPUEBEE, withlookup(GDPP, [(0.0, 0.0), (10.0, 4.0), (20.0, 7.0), (30.0, 9.0), (50.0, 12.0), (65.0, 13.0)]))
    add_equation(eqs, TPPUFFNEUBEE, withlookup(GDPP, [(0.0, 0.3), (15.0, 2.0), (25.0, 3.1), (35.0, 4.0), (50.0, 5.0)]))
    add_equation(eqs, DEBNE, (POP * TPPUEBEE * exp(-NIEE * (t - 1980))) / EEPI2022)
    add_equation(eqs, DFFNEUBNE, (POP * TPPUFFNEUBEE * exp(-NIEE * (t - 1980))) / EEPI2022)
    add_equation(eqs, FNE, FNE1980 + ramp(t, (FNE2022 - FNE1980) / 42, 1980, 2022) + ramp(t, (GFNE - FNE2022) / IPP, 2022, 2022 + IPP))
    add_equation(eqs, ERDNEFFFNE, FNE * DFFNEUBNE)
    add_equation(eqs, CNE, (ECRUNEFF / 1000) * ERDNEFFFNE)
    add_equation(eqs, EIDEFNE, ERDNEFFFNE * EUEPRUNEFF)
    add_equation(eqs, DFFFNEU, DFFNEUBNE - ERDNEFFFNE)
    add_equation(eqs, UFF, DFFFNEU + FFE)
    add_equation(eqs, DE, DEBNE + EIDEFNE)
    add_equation(eqs, DRES, REFF1980 + ramp(t, (REFF2022 - REFF1980) / 42, 1980, 2022) + ramp(t, (GREF - REFF2022) / IPP, 2022, 2022 + IPP))
    add_equation(eqs, DSRE, DE * DRES)
    add_equation(eqs, DREC, DSRE / RCUT)
    add_equation(eqs, DRECC, DREC - REC)
    add_equation(eqs, D(REC), AREC - DIREC)
    add_equation(eqs, AREC, max(0, (DRECC / RECT) + (DIREC)))
    add_equation(eqs, DIREC, REC / LREC)
    add_equation(eqs, ASWC, AREC)
    add_equation(eqs, D(ACSWCF1980), ASWC)
    add_equation(eqs, NDSWC, log(2) + log(ACSWCF1980 / SWC1980))
    add_equation(eqs, CISWC, (1 - CRDSWC)**NDSWC)
    add_equation(eqs, CAPEXRED, CAPEXRE1980 * CISWC)
    add_equation(eqs, CAPEXREG, CAPEXRED * AREC)
    add_equation(eqs, OPEXREG, OPEXRED * REP)
    add_equation(eqs, CRE, CAPEXREG + OPEXREG)
    add_equation(eqs, CAPEXFEG, CAPEXFED * AFEC)
    add_equation(eqs, OPEXFEG, OPEXFED * FEP)
    add_equation(eqs, CFE, CAPEXFEG + OPEXFEG)
    add_equation(eqs, CEL, CFE + CRE + CNEL)
    add_equation(eqs, REP, REC * RCUT)
    add_equation(eqs, GHMH2, REP * FREH / KWEPKGH2)
    add_equation(eqs, GHMt, GHMH2 * TPTH2)
    add_equation(eqs, RHP, BEM + GHMt)
    add_equation(eqs, TWEPEJEE, TWHPEJCE * EFPP)
    add_equation(eqs, IIASAREP, REP / TWEPEJEE + RHP / MTPEJCE)
    add_equation(eqs, FTWEPMt, TWEPEJEE / MTPEJCE)
    add_equation(eqs, IIASAFEP, UFF / MTPEJCE)
    add_equation(eqs, LCEP, REP + NEP)
    add_equation(eqs, DFE, max(0, DE - LCEP))
    add_equation(eqs, DFEC, DFE / EKHPY)
    add_equation(eqs, DFECC, (DFEC - FEC) / FECCT + DIFEC)
    add_equation(eqs, AFEC, max(0, DFECC))
    add_equation(eqs, D(FEC), AFEC - DIFEC)
    add_equation(eqs, LFEC, NLFEC * FCUTLOFC)
    add_equation(eqs, DIFEC, FEC / LFEC)
    add_equation(eqs, FCUT, DFE / FEC)
    add_equation(eqs, FCUTLOFC, 1 + sFCUTLOFC * ((FCUT / EKHPY) - 1))
    add_equation(eqs, FEP, FEC * FCUT)
    add_equation(eqs, NC, withlookup(t, [(1980.0, 75.0), (2000.0, 310.0), (2020.0, 310.0), (2098.9, 310.0)]))
    add_equation(eqs, NEP, NC * NCUT)
    add_equation(eqs, EP, FEP + NEP + REP)
    add_equation(eqs, ELB, EP / DE)
    add_equation(eqs, FFPNE, (FEP + NEP) / EP)
    add_equation(eqs, EU, DFFFNEU + EP / FTWEPMt + RHP)
    add_equation(eqs, EUPP, EU / POP)
    add_equation(eqs, FFE, FEP / FTWEPMt)
    add_equation(eqs, TCEG, (DEBNE * TCE / 1000) * AFMCM)
    add_equation(eqs, TCFFFNEUG, (DFFNEUBNE * TCFFFNEU / 1000) * AFMCM)
    add_equation(eqs, CFFFNEU, (DFFFNEU * TCFFFNEU) / 1000)
    add_equation(eqs, CG, EP * TC)
    add_equation(eqs, TGC, DEBNE * TC)
    add_equation(eqs, TCEN, TCEG + TCFFFNEUG + TGC)
    add_equation(eqs, TCENSGDP, TCEN / GDP)
    add_equation(eqs, CE, CFFFNEU + CEL + CG + CNE + CCCSG + CAC)
    add_equation(eqs, RECTEC, CE / TCEN)
    add_equation(eqs, CESGDP, CE / GDP)
    add_equation(eqs, ECETSGDP, ifelse(t > 2022, (CE - TCEN) / GDP, 0))
    return sys


def energy_full_support(name="ene", params=None, inits=None, tables=None, ranges=None):
    """The Energy sector variables that other sectors provide, read from tabulated runs of the whole model instead."""
    params = _params if params is None else params
    inits = _inits if inits is None else inits
    tables = _tables if tables is None else tables
    ranges = _ranges if ranges is None else ranges
    sys = ODESystem(name)
    eqs = sys.equations

    CAC = sys.variable("CAC", description="Climate.Cost of Air Capture Gdollar/y")
    GDP = sys.variable("GDP", description="Inventory.GDP Gdollar/y")
    GDPP = sys.variable("GDPP", description="Population.GDP per Person kdollar/p/y")
    IPP = sys.variable("IPP", description="Wellbeing.Introduction Period for Policy y")
    POP = sys.variable("POP", description="POPulation.Population Mp")
    add_equation(eqs, CAC, interpolate(t, tables["CAC"], ranges["CAC"]))
    add_equation(eqs, GDPP, interpolate(t, tables["GDPP"], ranges["GDPP"]))
    add_equation(eqs, POP, interpolate(t, tables["POP"], ranges["POP"]))
    add_equation(eqs, IPP, interpolate(t, tables["IPP"], ranges["IPP"]))
    add_equation(eqs, GDP, interpolate(t, tables["GDP"], ranges["GDP"]))
    return sys


