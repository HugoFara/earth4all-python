"""Equations of the Demand sector.

Transcribed from `src/demand/subsystems.jl` of Earth4All.jl, which
transcribes the Vensim model. Each equation is kept on a single line,
however long, so that the three can be read side by side.
"""

from ..functions import add_equation, interpolate, pulse, ramp, smooth, step
from ..symbolics import D, ifelse, max, min, t
from ..system import ODESystem
from .initialisations import _inits
from .parameters import _params
from .tables import _ranges, _tables


def demand(name="dem", params=None, inits=None, tables=None, ranges=None):
    """The equations of the Demand sector."""
    params = _params if params is None else params
    inits = _inits if inits is None else inits
    tables = _tables if tables is None else tables
    ranges = _ranges if ranges is None else ranges
    sys = ODESystem(name)
    eqs = sys.equations

    BITRW = sys.parameter("BITRW", params["BITRW"], "Basic Income Tax Rate Workers")
    EETF2022 = sys.parameter("EETF2022", params["EETF2022"], "Extra Empowerment Tax From 2022 (share of NI)")
    EGTRF2022 = sys.parameter("EGTRF2022", params["EGTRF2022"], "Extra General Tax Rate From 2022")
    EPTF2022 = sys.parameter("EPTF2022", params["EPTF2022"], "Extra Pension Tax From 2022 (share of NI)")
    ETGBW = sys.parameter("ETGBW", params["ETGBW"], "Extra Transfer of Govmnt Budget to Workers")
    FETACPET = sys.parameter("FETACPET", params["FETACPET"], "Fraction of Extra TA Cost Paid by Extra Taxes")
    FETPO = sys.parameter("FETPO", params["FETPO"], "Fraction of Extra Taxes Paid by Owners")
    FGDC2022 = sys.parameter("FGDC2022", params["FGDC2022"], "Fraction of Govmnt Debt Cancelled in 2022 1/y")
    FT1980 = sys.parameter("FT1980", params["FT1980"], "Fraction Transferred in 1980")
    GCF = sys.parameter("GCF", params["GCF"], "Govmnt Consumption Fraction")
    GDDP = sys.parameter("GDDP", params["GDDP"], "Govmnt DrawDown Period y")
    GDPOSR = sys.parameter("GDPOSR", params["GDPOSR"], "sGDPeoOSR<0")
    GDPP1980 = sys.parameter("GDPP1980", params["GDPP1980"], "GDP per Person in 1980 kDollar/p/y")
    GEIC = sys.parameter("GEIC", params["GEIC"], "Goal for Extra Income from Commons (share of NI)")
    GITRO = sys.parameter("GITRO", params["GITRO"], "Goal for Income Tax Rate Owners")
    GPP = sys.parameter("GPP", params["GPP"], "Govmnt Payback Period y")
    GSF2022 = sys.parameter("GSF2022", params["GSF2022"], "Govmnt Stimulus From 2022 (share of NI)")
    INEQ1980 = sys.parameter("INEQ1980", params["INEQ1980"], "INEQuality in 1980")
    ITRO1980 = sys.parameter("ITRO1980", params["ITRO1980"], "Income Tax Rate Owners in 1980")
    ITRO2022 = sys.parameter("ITRO2022", params["ITRO2022"], "Income Tax Rate Owners in 2022")
    MATGF = sys.parameter("MATGF", params["MATGF"], "Mult to Avoid Transient in Govmnt Finance")
    MATWF = sys.parameter("MATWF", params["MATWF"], "Mult to Avoid Transient in Worker Finance")
    MGDB = sys.parameter("MGDB", params["MGDB"], "Max Govmnt Debt Burden y")
    MWDB = sys.parameter("MWDB", params["MWDB"], "Max Workers Debt Burden y")
    OSF1980 = sys.parameter("OSF1980", params["OSF1980"], "Owner Savings Fraction in 1980")
    STR = sys.parameter("STR", params["STR"], "Sales Tax Rate")
    TAB = sys.parameter("TAB", params["TAB"], "Time to Adjust Budget y")
    TAOC = sys.parameter("TAOC", params["TAOC"], "Time to Adjust Owner Consumption y")
    TAWC = sys.parameter("TAWC", params["TAWC"], "Time to Adjust Worker Consumption y")
    TINT = sys.parameter("TINT", params["TINT"], "Time to Implement New Taxes y")
    WCF = sys.parameter("WCF", params["WCF"], "Worker Consumption Fraction")
    WDP = sys.parameter("WDP", params["WDP"], "Worker Drawdown Period y")
    WPP = sys.parameter("WPP", params["WPP"], "Worker Payback Period y")
    BCIL = sys.variable("BCIL", description="Bank Cash Inflow from Lending GDollar/y")
    BCISNI = sys.variable("BCISNI", description="Bank Cash Inflow as Share of NI (1)")
    BITRO = sys.variable("BITRO", description="Basic Income Tax Rate Owners (1)")
    CANCD = sys.variable("CANCD", description="CANCellation of Debt GDollar/y")
    CD = sys.variable("CD", description="Consumption Demand GDollar/y")
    CFGB = sys.variable("CFGB", description="Cash Flow from Govmnt to Banks GDollar/y")
    CFWB = sys.variable("CFWB", description="Cash Flow from Workers to Banks GDollar/y")
    CONTR = sys.variable("CONTR", description="CONTRol: (C+G+S)/NI = 1")
    CPP = sys.variable("CPP", description="Consumption Per Person GDollar/y")
    CSGDP = sys.variable("CSGDP", description="Consumption Share of GDP (1)")
    EGTF2022 = sys.variable("EGTF2022", description="Extra General Tax From 2022 Gdollar/y")
    ETF2022 = sys.variable("ETF2022", inits["ETF2022"], "Extra Taxes From 2022 GDollar/y")
    ETTAF2022 = sys.variable("ETTAF2022", description="Extra Taxes for TAs From 2022 GDollar/y")
    FGBW = sys.variable("FGBW", inits["FGBW"], "Fraction of Govmnt Budget to Workers (1)")
    GCIN = sys.variable("GCIN", description="Govmnt Cash INflow GDollar/y")
    GD = sys.variable("GD", 28087 * params["MATGF"], "Govmnt Debt Gdollar")
    GDB = sys.variable("GDB", description="Govmnt Debt Burden y")
    GETF2022 = sys.variable("GETF2022", description="Goal for Extra Taxes From 2022 GDollar/y")
    GFGBW = sys.variable("GFGBW", description="Goal for Fraction of Govmnt Budget to Workers (1)")
    GFSNI = sys.variable("GFSNI", description="Govmnt Finance as Share of NI (1)")
    GGI = sys.variable("GGI", description="Govmnt Gross Income GDollar/y")
    GGIS = sys.variable("GGIS", description="Govmnt Gross Income (as Share of NI)")
    GIC = sys.variable("GIC", description="Govmnt Interest Cost GDollar/y")
    GIPC = sys.variable("GIPC", description="Govmnt Investment in Public Capacity GDollar/y")
    GND = sys.variable("GND", description="Govmnt New Debt GDollar/y")
    GNI = sys.variable("GNI", inits["GNI"], "Govmnt Net Income GDollar/y")
    GNISNI = sys.variable("GNISNI", description="Govmnt Net Income as Share of NI (1)")
    GP = sys.variable("GP", description="Govmnt Payback GDollar/y")
    GPU = sys.variable("GPU", description="Govmnt PUrchases GDollar/y")
    GS = sys.variable("GS", description="Govmnt Spending GDollar/y")
    GSGDP = sys.variable("GSGDP", description="Govmnt Share of GDP (1)")
    IC2022 = sys.variable("IC2022", description="Income from Commons from 2022 GDollar/y")
    INEQ = sys.variable("INEQ", description="INEQuality (1)")
    INEQI = sys.variable("INEQI", description="INEQuality Index (1980=1)")
    ITO = sys.variable("ITO", description="Income Tax Owners (1)")
    ITW = sys.variable("ITW", description="Income Tax Workers (1)")
    MGD = sys.variable("MGD", description="Max Govmnt Debt GDollar")
    MWD = sys.variable("MWD", description="Max Workers Debt GDollar")
    OC = sys.variable("OC", description="Owner Consumption GDollar/y")
    OCF = sys.variable("OCF", description="Owner Consumptin Fraction (1)")
    OCIN = sys.variable("OCIN", description="Owner Cash INflow GDollar/y")
    OI = sys.variable("OI", description="Owner Income GDollar/y")
    OOIAT = sys.variable("OOIAT", description="Owner Operating Income After Tax GDollar/y")
    OS = sys.variable("OS", description="Owner Savings GDollar/y")
    OSF = sys.variable("OSF", description="Owner Savings Fraction (1)")
    OT = sys.variable("OT", description="Owner Taxes GDollar/y")
    OTR = sys.variable("OTR", description="Owner Tax Rate (1)")
    PGCIN = sys.variable("PGCIN", inits["PGCIN"], "Permanent Govmnt Cash INflow GDollar/y")
    POCI = sys.variable("POCI", inits["POCI"], "Permanent Owner Cash Inflow GDollar/y")
    PWCIN = sys.variable("PWCIN", inits["PWCIN"], "Permanent Worker Cash INflow GDollar/y")
    SSGDP = sys.variable("SSGDP", description="Savings Share of GDP (1)")
    ST = sys.variable("ST", description="Sales Tax GDollar/y")
    STO = sys.variable("STO", description="Sales Tax Owners GDollar/y")
    STW = sys.variable("STW", description="Sales Tax Workers GDollar/y")
    TP = sys.variable("TP", description="Transfer Payments GDollar/y")
    TPP = sys.variable("TPP", description="Total Purchasing Power GDollar/y")
    TS = sys.variable("TS", description="Total Savings GDollar/y")
    WCD = sys.variable("WCD", description="Worker consumption demand GDollar/y")
    WCIN = sys.variable("WCIN", description="Worker Cash INflow GDollar/y")
    WD = sys.variable("WD", 18992 * params["MATWF"], "Workers Debt GDollar")
    WDB = sys.variable("WDB", description="Worker Debt Burden y")
    WDI = sys.variable("WDI", description="Worker Disposable Income kDollar/p/y")
    WFCSI = sys.variable("WFCSI", description="Worker Finance Cost as Share of Income (1)")
    WI = sys.variable("WI", description="Worker Income GDollar/y")
    WIAT = sys.variable("WIAT", description="Worker Income After Tax GDollar/y")
    WIC = sys.variable("WIC", description="Worker Interest Cost GDollar/y")
    WND = sys.variable("WND", description="Workers New Debt GDollar/y")
    WP = sys.variable("WP", description="Workers Payback GDollar/y")
    WS = sys.variable("WS", description="Worker Savings GDollar/y")
    WT = sys.variable("WT", description="Worker Taxes GDollar/y")
    WTR = sys.variable("WTR", description="Worker Tax Rate (1)")
    ECTAF2022 = sys.variable("ECTAF2022")
    EGDPP = sys.variable("EGDPP")
    GBC = sys.variable("GBC")
    IPP = sys.variable("IPP")
    NI = sys.variable("NI")
    POP = sys.variable("POP")
    WBC = sys.variable("WBC")
    WF = sys.variable("WF")
    WSO = sys.variable("WSO")
    add_equation(eqs, BCIL, CFWB + CFGB)
    add_equation(eqs, BCISNI, BCIL / NI)
    add_equation(eqs, BITRO, min(1, ITRO1980) + ramp(t, (ITRO2022 - ITRO1980) / 42, 1980, 2022) + ramp(t, (GITRO - ITRO2022) / 78, 2022, 2100))
    add_equation(eqs, CANCD, pulse(t, 2022, 1) * GD * FGDC2022)
    add_equation(eqs, CD, WCD - STW + OC - STO)
    add_equation(eqs, CFGB, GIC + GP - GND)
    add_equation(eqs, CFWB, WIC + WP - WND)
    add_equation(eqs, CPP, CD / POP)
    add_equation(eqs, CSGDP, CD / NI)
    add_equation(eqs, CONTR, CSGDP + GSGDP + SSGDP)
    add_equation(eqs, EGTF2022, ifelse(t > 2022, EGTRF2022 + EETF2022 + EPTF2022, 0) * NI)
    smooth(eqs, ETF2022, GETF2022, TINT)
    add_equation(eqs, ETTAF2022, ifelse(t > 2022, ECTAF2022 * FETACPET, 0))
    smooth(eqs, FGBW, GFGBW, TINT)
    add_equation(eqs, GCIN, GNI - CFGB)
    add_equation(eqs, D(GD), GND - CANCD - GP)
    add_equation(eqs, GDB, GD / NI)
    add_equation(eqs, GETF2022, EGTF2022 + ETTAF2022)
    add_equation(eqs, GFGBW, FT1980 + ifelse(t > 2022, ETGBW, 0))
    add_equation(eqs, GFSNI, (GIC + GP) / NI)
    add_equation(eqs, GGI, WT + OT + STO + STW + IC2022)
    add_equation(eqs, GGIS, GGI / NI)
    add_equation(eqs, GIC, GD * GBC)
    add_equation(eqs, GIPC, PGCIN - GPU)
    add_equation(eqs, GND, max(0, (MGD - GD) / GDDP) + step(t, GSF2022, 2022) * NI)
    add_equation(eqs, GNI, (WT + OT + STO + STW + IC2022) - TP + ST)
    add_equation(eqs, GNISNI, GNI / NI)
    add_equation(eqs, GP, GD / GPP)
    add_equation(eqs, GPU, PGCIN * GCF)
    add_equation(eqs, GS, GPU + GIPC)
    add_equation(eqs, GSGDP, GS / NI)
    add_equation(eqs, IC2022, NI * ifelse(t > 2022, ramp(t, GEIC / IPP, 2022, 2020 + IPP), 0))
    add_equation(eqs, INEQ, OOIAT / WIAT)
    add_equation(eqs, INEQI, INEQ / INEQ1980)
    add_equation(eqs, ITO, BITRO * NI * (1 - WSO))
    add_equation(eqs, ITW, BITRW * NI * WSO)
    add_equation(eqs, MGD, NI * MGDB)
    add_equation(eqs, MWD, WI * MWDB)
    add_equation(eqs, OC, POCI * OCF)
    add_equation(eqs, OCF, 1 - OSF)
    add_equation(eqs, OCIN, OOIAT)
    add_equation(eqs, OI, NI * (1 - WSO))
    add_equation(eqs, OOIAT, OI - OT)
    add_equation(eqs, OS, POCI - OC)
    add_equation(eqs, OSF, OSF1980 * (1 + GDPOSR * (EGDPP / GDPP1980 - 1)))
    add_equation(eqs, OT, ITO + ETF2022 * FETPO)
    add_equation(eqs, OTR, OT / OI)
    smooth(eqs, PGCIN, GCIN, TAB)
    smooth(eqs, POCI, OCIN, TAOC)
    smooth(eqs, PWCIN, WCIN, TAWC)
    add_equation(eqs, SSGDP, TS / NI)
    add_equation(eqs, ST, STW + STO)
    add_equation(eqs, STO, OC * STR)
    add_equation(eqs, STW, WCD * STR)
    add_equation(eqs, TP, (WT + OT + STO + STW + IC2022) * FGBW)
    add_equation(eqs, TPP, WCIN + GCIN + OCIN - ST)
    add_equation(eqs, TS, OS + WS)
    add_equation(eqs, WCD, PWCIN * WCF)
    add_equation(eqs, WCIN, WIAT - CFWB)
    add_equation(eqs, D(WD), WND - WP)
    add_equation(eqs, WDI, PWCIN / WF)
    add_equation(eqs, WFCSI, CFWB / WIAT)
    add_equation(eqs, WI, NI * WSO)
    add_equation(eqs, WIAT, WI - WT + TP)
    add_equation(eqs, WIC, WD * WBC)
    add_equation(eqs, WT, ITW + ETF2022 * (1 - FETPO))
    add_equation(eqs, WTR, WT / WI)
    add_equation(eqs, WND, max(0, (MWD - WD) / WDP))
    add_equation(eqs, WP, WD / WPP)
    add_equation(eqs, WDB, WD / WIAT)
    add_equation(eqs, WS, PWCIN - WCD)
    return sys


def demand_full_support(name="dem", params=None, inits=None, tables=None, ranges=None):
    """The Demand sector variables that other sectors provide, read from tabulated runs of the whole model instead."""
    params = _params if params is None else params
    inits = _inits if inits is None else inits
    tables = _tables if tables is None else tables
    ranges = _ranges if ranges is None else ranges
    sys = ODESystem(name)
    eqs = sys.equations

    ECTAF2022 = sys.variable("ECTAF2022", description="Public.Extra Cost of TAs from 2022 Gdollar/y")
    EGDPP = sys.variable("EGDPP", description="Population.Effective GDP per person kDollar/p/y")
    GBC = sys.variable("GBC", description="Finance.Govmnt borrowing cost 1/y")
    IPP = sys.variable("IPP", description="Wellbeing.Introduction period for policy y")
    NI = sys.variable("NI", description="Inventory.National income GDollar/y")
    POP = sys.variable("POP", description="Population.Population Mp")
    WBC = sys.variable("WBC", description="Finance.Worker borrowing cost 1/y")
    WF = sys.variable("WF", description="Labour and market.Work force Mp")
    WSO = sys.variable("WSO", description="Labour and market.Worker Share of Output (1)")
    add_equation(eqs, ECTAF2022, interpolate(t, tables["ECTAF2022"], ranges["ECTAF2022"]))
    add_equation(eqs, EGDPP, interpolate(t, tables["EGDPP"], ranges["EGDPP"]))
    add_equation(eqs, GBC, interpolate(t, tables["GBC"], ranges["GBC"]))
    add_equation(eqs, NI, interpolate(t, tables["NI"], ranges["NI"]))
    add_equation(eqs, IPP, interpolate(t, tables["IPP"], ranges["IPP"]))
    add_equation(eqs, POP, interpolate(t, tables["POP"], ranges["POP"]))
    add_equation(eqs, WBC, interpolate(t, tables["WBC"], ranges["WBC"]))
    add_equation(eqs, WF, interpolate(t, tables["WF"], ranges["WF"]))
    add_equation(eqs, WSO, interpolate(t, tables["WSO"], ranges["WSO"]))
    return sys


